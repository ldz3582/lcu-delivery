def _spacer(h, n=1, pt=10):
    for _ in range(n):
        p = h.doc.add_paragraph()
        p.paragraph_format.space_before = Pt(0)
        p.paragraph_format.space_after = Pt(0)
        p.paragraph_format.line_spacing = Pt(pt)
        r = p.add_run("")
        r.font.size = Pt(2)


